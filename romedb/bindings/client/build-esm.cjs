'use strict';
// Writes client.mjs and values.mjs, the entries for Workers, browsers and other
// non-Node runtimes, from client.cjs and values.cjs. Each .mjs file wraps the
// unchanged CommonJS source, so both formats run the same code.
// Run `node build-esm.cjs` after editing either source; `--check` fails when an
// .mjs file is out of date.
const fs = require('node:fs');
const path = require('node:path');

const MODULES = [
  { source: 'values.cjs', output: 'values.mjs', imports: {}, empty: [], unavailable: {} },
  {
    source: 'client.cjs',
    output: 'client.mjs',
    imports: { './values.cjs': './values.mjs' },
    empty: ['./client-internal.cjs'],
    unavailable: { './request-journal.cjs': 'saveRequest and loadRequest need Node.js file access; store the PreparedWrite yourself' },
  },
];

function generate(module) {
  const source = fs.readFileSync(path.join(__dirname, module.source), 'utf8');
  const known = new Set([...Object.keys(module.imports), ...module.empty, ...Object.keys(module.unavailable)]);
  for (const [, specifier] of source.matchAll(/\brequire\(([^)]*)\)/g)) {
    if (!known.has(specifier.slice(1, -1))) throw new Error(`${module.source} requires ${specifier}; add it to build-esm.cjs or remove it`);
  }
  const names = Object.keys(require(path.join(__dirname, module.source)));
  const imports = Object.entries(module.imports).map(([specifier, target], index) => [specifier, `module${index}`, target]);
  return [
    `// Generated by build-esm.cjs from ${module.source}. Edit ${module.source}, then run \`node build-esm.cjs\`.`,
    ...imports.map(([, name, target]) => `import * as ${name} from '${target}';`),
    '',
    'const commonjs = { exports: {} };',
    '(function (module, exports, require) {',
    source.trimEnd(),
    '})(commonjs, commonjs.exports, specifier => {',
    ...imports.map(([specifier, name]) => `  if (specifier === '${specifier}') return ${name};`),
    ...module.empty.map(specifier => `  if (specifier === '${specifier}') return {};`),
    ...Object.entries(module.unavailable).map(([specifier, message]) => `  if (specifier === '${specifier}') throw new TypeError(${JSON.stringify(message)});`),
    '  throw new TypeError(`Cannot load ${specifier}`);',
    '});',
    '',
    `export const { ${names.join(', ')} } = commonjs.exports;`,
    '',
  ].join('\n');
}

const check = process.argv.includes('--check');
const stale = [];
for (const module of MODULES) {
  const file = path.join(__dirname, module.output);
  const text = generate(module);
  if (check) {
    if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== text) stale.push(module.output);
  } else fs.writeFileSync(file, text);
}
if (stale.length) {
  process.stderr.write(`${stale.join(', ')} out of date; run node build-esm.cjs\n`);
  process.exitCode = 1;
}
